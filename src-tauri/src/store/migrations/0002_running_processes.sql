-- Миграция 0002 — учёт запущенных внешних программ.
--
-- Нужна ради уборки при запуске: гарантии на Windows и Linux не равны, и на Linux
-- внук, порождённый внешней программой, переживает аварийную смерть приложения.
-- Записи здесь относятся к ТЕКУЩЕМУ запуску; при старте таблица разбирается и очищается.

CREATE TABLE running_processes (
    pid        INTEGER PRIMARY KEY,
    -- Имя программы. Сверяется перед завершением: номера процессов переиспользуются,
    -- и за старым номером может оказаться посторонняя программа.
    program    TEXT NOT NULL,
    task_id    TEXT REFERENCES tasks (id) ON DELETE CASCADE,
    started_at TEXT NOT NULL
);
