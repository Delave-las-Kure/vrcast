-- Миграция 0004 — точное опознание процесса при уборке.
--
-- Зачем. Уборка при запуске добивает программы, уцелевшие от прошлого запуска,
-- и перед этим обязана убедиться, что за номером процесса не оказалась посторонняя
-- программа: номера переиспользуются, и убить чужое дороже, чем не добить своё.
--
-- Сверка по имени эту задачу не решает. Поймано непрерывной интеграцией под Linux
-- 2026-08-25 на живом примере: `sh -c "sleep 300"` заменяет себя на `sleep`, и имя
-- перестаёт совпадать с записанным. Плюс `/proc/<pid>/comm` обрезан пятнадцатью
-- знаками, так что программа с длинным именем не совпадёт сама с собой.
--
-- Решение — время запуска процесса. Оно не меняется при подмене образа, не обрезается
-- и различает два процесса с одним номером надёжнее любого имени.

ALTER TABLE running_processes ADD COLUMN identity TEXT;
