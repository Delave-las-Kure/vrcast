-- Миграция 0003 — кеш библиотеки и разобранные параметры файлов.
--
-- Зачем кеш. Библиотека живёт на сервере, а показать её надо мгновенно: список из
-- полусотни медиа по медленному каналу читается секунды, и всё это время смотреть
-- на пустой экран пользователю незачем. Поэтому показывается последнее известное
-- состояние, а обновление приходит следом событием.
--
-- Второе назначение — работа при недоступном сервере. Пустой экран в этом случае
-- неотличим от «библиотека пропала», и это худшее, что можно показать человеку.

CREATE TABLE library_cache (
    server_id  TEXT PRIMARY KEY
               REFERENCES server_profiles (id) ON DELETE CASCADE,
    -- Готовый ответ команды. Хранится целиком, а не по полям: это снимок для показа,
    -- запросов к нему не делают, а разбирать его на таблицы значит держать две схемы
    -- одного и того же в согласии.
    view_json  TEXT NOT NULL,
    updated_at TEXT NOT NULL
);

-- Параметры файлов, вычитанные из заголовка MP4.
--
-- Кешируются потому, что стоят дорого: ради каждого файла надо забрать с сервера
-- сотни килобайт его начала. Перечитывать это при каждом открытии библиотеки —
-- значит качать десятки мегабайт на ровном месте.
CREATE TABLE file_params (
    server_id     TEXT NOT NULL
                  REFERENCES server_profiles (id) ON DELETE CASCADE,
    path          TEXT NOT NULL,
    -- Размер на момент разбора. Изменился — значит файл заменили, и параметры
    -- надо читать заново: та же длительность у файла другого размера означала бы
    -- неверный битрейт.
    size_bytes    INTEGER NOT NULL,
    duration_s    REAL,
    width         INTEGER,
    height        INTEGER,
    bitrate_bps   INTEGER,
    video_codec   TEXT,
    audio_codec   TEXT,
    -- NULL = вопрос остался открытым (заголовка не хватило, файл не MP4).
    faststart_ok  INTEGER
                  CHECK (faststart_ok IS NULL OR faststart_ok IN (0, 1)),
    probed_at     TEXT NOT NULL,
    PRIMARY KEY (server_id, path)
);
