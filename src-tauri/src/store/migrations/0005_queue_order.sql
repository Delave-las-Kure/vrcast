-- T096 — порядок очереди (FR-083).
--
-- Без явного порядка очередь — это «кто первым захватил блокировку», а переставить
-- в ней ничего нельзя: переставлять нечего. Номер отдельным полем, а не по времени
-- создания: перестановка обязана менять порядок, не подделывая время.
ALTER TABLE tasks ADD COLUMN queue_order INTEGER NOT NULL DEFAULT 0;

-- Уже лежащим задачам порядок задаётся по времени появления: у них он до сих пор
-- и был таким, просто не назывался.
UPDATE tasks SET queue_order = rowid;
