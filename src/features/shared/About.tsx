/**
 * T107 — «О программе»: где взять исходный код раздаваемой версии.
 *
 * Это не украшение и не формальность. Приложение распространяется собранным
 * файлом под GPL-3.0-or-later, а GPL требует, чтобы получивший сборку мог
 * получить и её исходный код. Ссылка обязана указывать на **ту же** версию,
 * что у него на руках, — потому здесь показан номер версии, полученный от ядра,
 * а не написанный в разметке: разойдясь с настоящим, он превратил бы
 * обязательство в обманку.
 *
 * Перечень чужих работ, входящих в поставку, собирается сборкой в THIRD-PARTY.md
 * (см. `scripts/gen-third-party.mjs`). Здесь на него указано, а не повторено:
 * список в двадцать тысяч строк на экране никому не помощь, а копия, которую
 * забудут обновить, — хуже отсутствия.
 */

import { useEffect, useState } from "react";
import { ipc } from "../../shared/ipc";

/** Где лежит исходный код. Обязательство GPL, а не ссылка «для интереса». */
const SOURCE_URL = "https://github.com/Delave-las-Kure/vrcast";

export function About() {
  const [version, setVersion] = useState<string | null>(null);
  const [schema, setSchema] = useState<number | null>(null);

  useEffect(() => {
    ipc
      .appVersions()
      .then((v) => {
        setVersion(v.app);
        setSchema(v.schema);
      })
      .catch(() => {
        setVersion(null);
        setSchema(null);
      });
  }, []);

  return (
    <div className="panel">
      <h1>О программе</h1>

      <p>
        <strong>VRCast Studio</strong>
        {version ? ` ${version}` : ""} — управление стриминг-сервером: библиотека,
        подготовка файлов, заливка, зрители.
      </p>

      <h2>Лицензия и исходный код</h2>
      <p>
        Приложение распространяется на условиях{" "}
        <strong>GNU General Public License версии 3 или новее</strong>. Это значит,
        что вы вправе им пользоваться, изучать его, изменять и передавать дальше —
        и что получивший от вас сборку имеет те же права.
      </p>
      <p>
        Исходный код <em>этой самой версии</em>
        {version ? <> (метка <code>v{version}</code>)</> : null} доступен по адресу:
      </p>
      <p>
        <a href={SOURCE_URL} target="_blank" rel="noreferrer">
          {SOURCE_URL}
        </a>
      </p>
      <p className="muted">
        Если по этому адресу исходного кода не окажется, напишите нам — мы обязаны
        его предоставить, и это не любезность, а условие лицензии.
      </p>

      <h2>Чужие работы в поставке</h2>
      <p>
        В приложение входят сторонние библиотеки и полная сборка FFmpeg, каждая
        со своими условиями. Полный перечень с текстами лицензий лежит в файле{" "}
        <code>THIRD-PARTY.md</code> рядом с исходным кодом; он собирается из дерева
        зависимостей при сборке, а не пишется руками, — иначе устарел бы в первый же
        месяц.
      </p>
      <p>
        <a href={`${SOURCE_URL}/blob/main/THIRD-PARTY.md`} target="_blank" rel="noreferrer">
          Перечень сторонних компонентов
        </a>
      </p>

      {schema !== null && (
        <p className="muted">
          Версия локального хранилища: {schema}. Это нужно при разборе неполадок.
        </p>
      )}
    </div>
  );
}
